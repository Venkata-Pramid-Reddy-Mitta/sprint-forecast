#!/usr/bin/env python
"""Render the architecture diagram to a committed SVG, with no browser and no Mermaid.

GitHub refuses to render a Mermaid fence reliably, and a Mermaid SVG embedded with <img>
breaks in several documented ways (html labels, percentage width, transparent background).
This tool sidesteps all of that: it writes a plain, valid SVG with intrinsic width and
height from the viewBox, a painted light background, and text labels as <text>, so the
image renders identically on GitHub, in a preview, and in a PDF.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "diagram"

W, H = 900, 540
BG = "#f7f8fa"
BOX = "#ffffff"
STROKE = "#334155"
ACCENT = "#1b4f72"
TEXT = "#111827"


def box(x, y, w, h, lines, fill=BOX, stroke=STROKE):
    label = "".join(
        f'<tspan x="{x + w / 2}" dy="{18 if i else 0}">{ln}</tspan>'
        for i, ln in enumerate(lines)
    )
    ty = y + h / 2 - (len(lines) - 1) * 9 + 5
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" '
        f'fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>'
        f'<text x="{x + w / 2}" y="{ty}" text-anchor="middle" '
        f'font-family="system-ui, sans-serif" font-size="13" fill="{TEXT}">{label}</text>'
    )


def arrow(x1, y1, x2, y2):
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{ACCENT}" '
        f'stroke-width="1.8" marker-end="url(#a)"/>'
    )


def build_svg() -> str:
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
        f'viewBox="0 0 {W} {H}">',
        '<defs><marker id="a" markerWidth="10" markerHeight="10" refX="8" refY="3" '
        'orient="auto" markerUnits="strokeWidth">'
        f'<path d="M0,0 L8,3 L0,6 Z" fill="{ACCENT}"/></marker></defs>',
        f'<rect x="0" y="0" width="{W}" height="{H}" fill="{BG}"/>',
        f'<text x="{W / 2}" y="30" text-anchor="middle" font-family="system-ui, sans-serif" '
        f'font-size="17" font-weight="700" fill="{ACCENT}">sprint-forecast data flow</text>',
    ]
    # Inputs
    parts.append(box(40, 70, 180, 56, ["throughput history", "(past sprints)"]))
    parts.append(box(40, 150, 180, 56, ["backlog", "(items remaining)"]))
    # Validation
    parts.append(box(270, 110, 160, 56, ["validate", "(reject bad input)"]))
    # Engine
    parts.append(box(480, 110, 180, 56, ["Monte Carlo", "bootstrap sampler"], fill="#eef4fb"))
    # Distribution
    parts.append(box(700, 110, 160, 56, ["completion", "distribution"]))
    # Outputs row
    parts.append(box(480, 230, 180, 56, ["percentiles", "P50 / P85 / P95"]))
    parts.append(box(700, 230, 160, 56, ["committed date", "to probability"]))
    parts.append(box(480, 320, 380, 56, ["verdict: safe / unsafe / cannot answer",
                                         "exit 0 / 2 / 3"], fill="#eef4fb"))
    # Calibration lane
    parts.append(box(270, 430, 590, 70,
                     ["calibration engine: synthetic teams from a known distribution",
                      "grades each percentile (empirical vs nominal coverage)"],
                     fill="#fbf3ea"))
    # Arrows
    parts += [
        arrow(220, 98, 270, 125),
        arrow(220, 178, 270, 150),
        arrow(430, 138, 480, 138),
        arrow(660, 138, 700, 138),
        arrow(620, 166, 560, 230),
        arrow(780, 166, 780, 230),
        arrow(660, 258, 620, 320),
        arrow(780, 258, 700, 320),
        arrow(570, 166, 500, 320),
        arrow(560, 376, 560, 430),
    ]
    parts.append("</svg>")
    return "\n".join(parts)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    svg = build_svg()
    (OUT / "architecture.svg").write_text(svg)
    (OUT / "manifest.json").write_text(
        json.dumps({"file": "architecture.svg", "width": W, "height": H,
                    "note": "generated by tools/render_diagram.py, no browser required"},
                   indent=2) + "\n"
    )
    print(f"wrote {(OUT / 'architecture.svg').relative_to(ROOT)} ({len(svg)} bytes)")


if __name__ == "__main__":
    main()
